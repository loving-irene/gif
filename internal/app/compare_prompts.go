type compareMotionPreset struct {
	ID     string `json:"id"`
	Name   string `json:"name"`
	Prompt string `json:"prompt"`
}

// compareMotionPrefix 对应对比页的图序：image1=自拍，image2=定稿（与正式流程相反）。
// 动作文案后追加与正式生成相同的 5×5 规格段，保证横评的是同一套分格约束。
const compareMotionPrefix = `image1是本人自拍，只核对身份；image2是已确认角色定稿，只使用右侧全身造型锁定画风、服装、配色和5:1头身比，不输出近景。每一格都保持同一5:1头身比，不为动作拉长四肢或画大躯干；全程只有这一个角色，身体、四肢和鞋完整入格。服装沿用定稿。
`

